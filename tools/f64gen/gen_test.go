const root = "../.."

// TestGeneratedIsCurrent is -check inside the test suite: every committed float64
// file must be exactly what the generator writes from today's float32 sources, and
// no generated directory may hold a file the generator does not produce. A float32
// change that is not regenerated fails here, in CI, instead of drifting.
func TestGeneratedIsCurrent(t *testing.T) {
	files, err := generate(root)
	if err != nil {
		t.Fatal(err)
	}
	if len(files) == 0 {
		t.Fatal("generator produced nothing, so the comparison below would pass vacuously")
	}
	for path, want := range files {
		got, err := os.ReadFile(filepath.Join(root, path))
		if err != nil {
			t.Errorf("%s: %v (run `go run ./tools/f64gen` from the repository root)", path, err)
			continue
		}
		if !bytes.Equal(got, want) {
			t.Errorf("%s is stale: run `go run ./tools/f64gen` from the repository root", path)
		}
	}
	extra, err := orphans(root, files)
	if err != nil {
		t.Fatal(err)
	}
	for _, p := range extra {
		t.Errorf("%s: generated directory holds a file with no float32 source", p)
	}
}

// TestDriftCheckCanFail is TestGeneratedIsCurrent's positive control: a one-token
// change to a float32 source must make the generated bytes differ from the
// committed copy. Without it, a comparison against the wrong root, or one that
// read the same file twice, would pass and look like coverage.
func TestDriftCheckCanFail(t *testing.T) {
	tmp := t.TempDir()
	for _, p := range pkgs {
		if err := os.MkdirAll(filepath.Join(tmp, p.src), 0o755); err != nil {
			t.Fatal(err)
		}
		srcs, _ := filepath.Glob(filepath.Join(root, p.src, "*.go"))
		for _, s := range srcs {
			b, err := os.ReadFile(s)
			if err != nil {
				t.Fatal(err)
			}
			if filepath.Base(s) == "pack.go" && p.src == "internal/pack" {
				b = bytes.Replace(b, []byte("int(64 / unsafe.Sizeof"), []byte("int(32 / unsafe.Sizeof"), 1)
			}
			if err := os.WriteFile(filepath.Join(tmp, p.src, filepath.Base(s)), b, 0o644); err != nil {
				t.Fatal(err)
			}
		}
	}
	files, err := generate(tmp)
	if err != nil {
		t.Fatal(err)
	}
	committed, err := os.ReadFile(filepath.Join(root, "internal/pack64/pack.go"))
	if err != nil {
		t.Fatal(err)
	}
	if bytes.Equal(files["internal/pack64/pack.go"], committed) {
		t.Fatal("a changed float32 source generated the committed bytes: the drift check cannot see a change")
	}
}

// TestNoFloat32Survives parses every generated file and requires that no
// identifier float32 remains: the rewrite is total, and a float32 buffer or
// conversion left in the float64 middle would silently halve its precision.
// (Comments may still say float32; they are the original's prose.)
func TestNoFloat32Survives(t *testing.T) {
	files, err := generate(root)
	if err != nil {
		t.Fatal(err)
	}
	for path, src := range files {
		f, err := parser.ParseFile(token.NewFileSet(), path, src, 0)
		if err != nil {
			t.Fatalf("%s: %v", path, err)
		}
		ast.Inspect(f, func(n ast.Node) bool {
			if id, ok := n.(*ast.Ident); ok && id.Name == "float32" {
				t.Errorf("%s: identifier float32 survived the rewrite", path)
			}
			return true
		})
		if !strings.Contains(string(src), "Code generated by tools/f64gen") {
			t.Errorf("%s: no generated-code header", path)
		}
	}
}

// TestUnknownKernSelectorIsRefused pins the rule that a new dependency of the middle
// on kern needs a float64 decision: the generator must fail, not copy it across.
func TestUnknownKernSelectorIsRefused(t *testing.T) {
	dir := t.TempDir()
	src := "// Copyright 2026 Scott Friedman\n// SPDX-License-Identifier: Apache-2.0\n\npackage block\n\nimport \"github.com/scttfrdmn/keel/internal/kern\"\n\nvar _ = kern.Preferred\n"
	path := filepath.Join(dir, "x.go")
	if err := os.WriteFile(path, []byte(src), 0o644); err != nil {
		t.Fatal(err)
	}
	if _, err := transform(path, "internal/block/x.go", "block64"); err == nil || !strings.Contains(err.Error(), "kern.Preferred") {
		t.Fatalf("transform accepted an undecided kern selector (err = %v)", err)
	}
}
